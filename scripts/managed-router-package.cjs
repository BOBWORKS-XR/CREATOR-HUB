const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');

function routeFiles(platform) {
  return [`routing/creator-hub-mcp-router${platform === 'windows' ? '.exe' : ''}`,
    'routing/router.json', 'routing/router.minisig', 'routing/runtime.json', 'routing/runtime.minisig'];
}
function signingKey(root) {
  const key = process.env.CREATOR_HUB_SIGNING_KEY_PATH;
  if (!key || !path.isAbsolute(key) || !fs.statSync(key).isFile()) throw Error('Configure the existing release-signing key outside the repository; no key is generated by this builder.');
  const relative = path.relative(fs.realpathSync(root), fs.realpathSync(key));
  if (!relative.startsWith(`..${path.sep}`) && !path.isAbsolute(relative)) throw Error('The release-signing key must remain outside the repository.');
  return key;
}
function signDetached(file, key) {
  if (fs.existsSync(`${file}.sig`)) throw Error('Refusing to replace an existing signature.');
  const result = spawnSync(process.execPath, [require.resolve('@tauri-apps/cli/tauri.js'), 'signer', 'sign', '-f', key, file], {
    windowsHide: true, encoding: 'utf8', timeout: 30000,
    env: { ...process.env, TAURI_SIGNING_PRIVATE_KEY_PASSWORD: process.env.CREATOR_HUB_SIGNING_PASSWORD || '' },
  });
  if (result.status !== 0) throw Error('Signing failed; signer output is withheld to protect key material.');
  const encoded = fs.readFileSync(`${file}.sig`, 'utf8').trim();
  const signature = Buffer.from(encoded, 'base64');
  if (signature.toString('base64') !== encoded || !signature.toString('utf8').startsWith('untrusted comment:')) throw Error('Invalid detached signature encoding.');
  return signature;
}
function prepare(directory, manifest, router, runtime, sign) {
  require('./build-unified.cjs').verifyStage(path.join(directory, 'modules'), manifest);
  const names = routeFiles(manifest.platform);
  const destination = path.join(directory, 'modules/routing');
  if (fs.existsSync(destination)) throw Error('Managed router output already exists.');
  const bytes = fs.readFileSync(runtime);
  if (bytes.length > 32768) throw Error('Runtime metadata is too large.');
  const descriptor = JSON.parse(bytes);
  const version = descriptor.hubVersion;
  if (JSON.stringify(descriptor) !== JSON.stringify(require('./mcp-runtime-descriptor.cjs').runtimeDescriptor(manifest, version))) throw Error('Runtime metadata does not match this package.');
  fs.mkdirSync(destination);
  const file = name => path.join(directory, 'modules', name);
  fs.copyFileSync(router, file(names[0]), fs.constants.COPYFILE_EXCL);
  fs.chmodSync(file(names[0]), 0o755);
  const identity = { schemaVersion: 1, product: 'com.creatorworks.hub.mcp-router',
    platform: manifest.platform, arch: manifest.arch, protocol: 1, sha256: hash(file(names[0])) };
  fs.writeFileSync(file(names[1]), JSON.stringify(identity), { flag: 'wx' });
  fs.writeFileSync(file(names[2]), sign(file(names[1])), { flag: 'wx' });
  fs.writeFileSync(file(names[3]), bytes, { flag: 'wx' });
  fs.writeFileSync(file(names[4]), sign(file(names[3])), { flag: 'wx' });
  return { protocol: 1, files: Object.fromEntries(names.map(name => [name, hash(file(name))])) };
}
module.exports = { routeFiles, signingKey, signDetached, prepare };
