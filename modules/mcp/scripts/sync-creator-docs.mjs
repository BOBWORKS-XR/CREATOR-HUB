import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const repository = 'SideQuestVR/BanterSDK';
const maxPageBytes = 128 * 1024;
const maxTotalBytes = 1024 * 1024;
const reviewedLicenseSha256 = '13a77431376172fc19640b667dd2b1c689e5a013ebf5fa8fa93f58f9c5b66504';
export const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
export const blobHash = bytes => createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex');

async function read(url, max, fetcher) {
  const response = await fetcher(url, { redirect: 'error', signal: AbortSignal.timeout(30000) });
  assert.equal(response.status, 200, `Documentation fetch failed: ${url}`);
  const chunks = [];
  let length = 0;
  for await (const chunk of response.body) {
    length += chunk.length;
    assert.ok(length <= max, 'Documentation input exceeds bounds');
    chunks.push(chunk);
  }
  return Buffer.concat(chunks);
}

export async function collectCreatorDocs(revision, fetcher = fetch) {
  assert.match(revision, /^[a-f0-9]{40}$/, 'An explicit immutable SDK commit is required');
  const treeBytes = await read(`https://api.github.com/repos/${repository}/git/trees/${revision}?recursive=1`,
    8 * 1024 * 1024, fetcher);
  const tree = JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(treeBytes));
  assert.equal(tree.truncated, false, 'Refuse incomplete SDK trees');
  assert.ok(Array.isArray(tree.tree), 'Invalid SDK tree');
  const selected = tree.tree.filter(entry => entry.type === 'blob' &&
    (entry.path === 'LICENSE.md' || /^Docs\/(?:[a-z0-9-]+\/)*[A-Za-z0-9_-]+\.md$/.test(entry.path)))
    .sort((a, b) => a.path.localeCompare(b.path, 'en'));
  assert.ok(selected.length > 2 && selected.length <= 100, 'Unexpected documentation page count');
  assert.equal(new Set(selected.map(entry => entry.path)).size, selected.length, 'Duplicate SDK paths');
  assert.ok(selected.some(entry => entry.path === 'LICENSE.md') &&
    selected.some(entry => entry.path === 'Docs/README.md') &&
    selected.some(entry => entry.path === 'Docs/_sidebar.md'), 'Missing SDK provenance inputs');
  const inputs = [];
  let total = 0;
  for (const entry of selected) {
    assert.match(entry.sha, /^[a-f0-9]{40}$/);
    assert.ok(Number.isSafeInteger(entry.size) && entry.size > 0 && entry.size <= maxPageBytes);
    const sourceUrl = `https://raw.githubusercontent.com/${repository}/${revision}/${entry.path}`;
    const bytes = await read(sourceUrl, maxPageBytes, fetcher);
    assert.equal(bytes.length, entry.size, `SDK size changed: ${entry.path}`);
    assert.equal(blobHash(bytes), entry.sha, `SDK content differs from pinned tree: ${entry.path}`);
    total += bytes.length;
    assert.ok(total <= maxTotalBytes, 'Documentation snapshot exceeds bounds');
    inputs.push({ path: entry.path, sourceUrl, blobSha: entry.sha, sha256: sha256(bytes),
      text: new TextDecoder('utf-8', { fatal: true }).decode(bytes) });
  }
  const license = inputs.find(input => input.path === 'LICENSE.md');
  assert.equal(license.sha256, reviewedLicenseSha256, 'Review changed SDK licence before importing');
  const sidebar = inputs.find(input => input.path === 'Docs/_sidebar.md');
  const pages = inputs.filter(input => ![license, sidebar].includes(input)).map(input => {
    const path = input.path.slice('Docs/'.length);
    const title = /^#\s+(.+)$/m.exec(input.text)?.[1];
    assert.ok(title && title.length <= 160, `Missing documentation title: ${path}`);
    return { ...input, path, title,
      url: `https://altvr.app/docs/${path === 'README.md' ? '' : path.replace(/\.md$/, '')}` };
  });
  return { schemaVersion: 1, siteUrl: 'https://altvr.app/docs/', repository: `https://github.com/${repository}`,
    branch: 'feature/greenfield', revision, license, sidebar, pages };
}

async function main() {
  assert.equal(process.argv.length, 4, 'Usage: node scripts/sync-creator-docs.mjs --revision COMMIT');
  assert.equal(process.argv[2], '--revision');
  const snapshot = await collectCreatorDocs(process.argv[3]);
  const output = fileURLToPath(new URL('../src/resources/creator-docs-snapshot.ts', import.meta.url));
  // Mechanical import only; API behaviour and catalogue definitions are maintained separately.
  await writeFile(output, `// Generated by scripts/sync-creator-docs.mjs from an immutable SDK revision.\n` +
    `// Upstream MIT licence is retained in snapshot.license and the resource index.\n` +
    `export const CREATOR_DOCS_SNAPSHOT = ${JSON.stringify(snapshot, null, 2)};\n`, 'utf8');
  console.log(JSON.stringify({ pages: snapshot.pages.length, revision: snapshot.revision, output }));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main().catch(error => {
  console.error(error.message); process.exitCode = 1;
});
